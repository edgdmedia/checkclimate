#!/usr/bin/env node
/**
 * Generate src/styles/tokens.css from design/system/project/tokens.json.
 *
 * The design system JSON is the source of truth. Keep token names unchanged:
 * a colour token `brand-forest` becomes `--brand-forest`, spacing token
 * `space-2` becomes `--space-2`, and so on. Light values live on :root and
 * dark overrides on [data-theme="dark"].
 */
import { readFile, writeFile, mkdir } from "node:fs/promises";
import { dirname, resolve } from "node:path";
import { fileURLToPath } from "node:url";

const root = resolve(dirname(fileURLToPath(import.meta.url)), "..");
const sourcePath = resolve(root, "design/system/project/tokens.json");
const outputPath = resolve(root, "src/styles/tokens.css");

const tokens = JSON.parse(await readFile(sourcePath, "utf8"));

/** @param {Record<string, unknown>} value */
function tokenValue(value) {
	if (typeof value === "string") return value;
	if (value && typeof value === "object" && "light" in value) return value.light;
	return null;
}

/** @param {Record<string, unknown>} value */
function darkValue(value) {
	if (value && typeof value === "object" && "dark" in value) return value.dark;
	if (value && typeof value === "object" && "light" in value) return value.light;
	return null;
}

const lines = [
	"/* Generated by scripts/build-tokens.mjs from design/system/project/tokens.json. */",
	"/* Do not edit by hand: run `pnpm dev` or `pnpm build`, or node scripts/build-tokens.mjs. */",
	"",
	":root {",
	"  color-scheme: light;",
	'  --font-display: "Red Hat Display", sans-serif;',
];

for (const token of tokens.color.tokens) {
	const value = tokenValue(token.value);
	if (!value) continue;
	lines.push(`  --${token.name}: ${value};`);
}

lines.push("  --link: var(--brand-forest);");

for (const group of tokens.type.groups) {
	for (const style of group.styles) {
		lines.push(`  --text-${style.name}-size: ${style.fontSize};`);
		lines.push(`  --text-${style.name}-line: ${style.lineHeight};`);
		lines.push(`  --text-${style.name}-weight: ${style.fontWeight};`);
	}
}

for (const token of tokens.spacing.tokens) lines.push(`  --${token.name}: ${token.value};`);
for (const token of tokens.radius.tokens) lines.push(`  --${token.name}: ${token.value};`);
for (const token of tokens.shadow.tokens) lines.push(`  --${token.name}: ${token.value};`);
for (const token of tokens.size.tokens) lines.push(`  --${token.name}: ${token.value};`);

lines.push("  --wrap-max: 1240px;", "  --wrap-gutter: 24px;", "}", "");

lines.push('[data-theme="dark"] {', "  color-scheme: dark;");
for (const token of tokens.color.tokens) {
	const value = darkValue(token.value);
	if (!value) continue;
	lines.push(`  --${token.name}: ${value};`);
}
lines.push("  --link: var(--brand-amber);", "}", "");

await mkdir(dirname(outputPath), { recursive: true });
await writeFile(outputPath, lines.join("\n"), "utf8");
console.log(`tokens.css written from ${sourcePath}`);